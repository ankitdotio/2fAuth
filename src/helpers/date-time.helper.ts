export const generateMinutesSeconds = (minutes: number) => minutes * 60;

export const generateMinutesMilliseconds = (minutes: number) =>
  minutes * 60 * 1000;

export const generateDaySeconds = (days: number) => days * 24 * 60 * 60;

export const generateDayMilliseconds = (days: number) =>
  days * 24 * 60 * 60 * 1000;
